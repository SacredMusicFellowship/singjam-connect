import { FIXED_NOW } from "../constants";
import type { Scenario } from "../types";
import { insert, jsonb, literal, raw, relativeTimestamp, textArray, uuidArray } from "./sql";

export type SeedFile = { name: string; sql: string };

const HEADER = `-- Generated by packages/test-fixtures (npm run seed:write). Do not edit by hand.
-- Entirely fake data for local Supabase, e2e tests and screenshots.
`;

// Supabase Auth's email/password sign-in reads these token columns as strings, so they must be ''
// rather than null, and each user needs an email identity.
const AUTH_INSTANCE = "00000000-0000-0000-0000-000000000000";

export function scenarioToSql(scenario: Scenario, anchor: Date = FIXED_NOW): SeedFile[] {
  const at = (iso: string | null) => relativeTimestamp(iso, anchor);
  const tagId = (type: string, name: string) =>
    raw(`(select id from public.tags where type = ${literal(type)} and name = ${literal(name)})`);

  const auth = [
    insert(
      "auth.users",
      scenario.authUsers.map((u) => ({
        instance_id: AUTH_INSTANCE,
        id: u.id,
        aud: "authenticated",
        role: "authenticated",
        email: u.email,
        encrypted_password: raw(`extensions.crypt(${literal(u.password)}, extensions.gen_salt('bf'))`),
        email_confirmed_at: at(u.created_at),
        raw_app_meta_data: jsonb({ provider: "email", providers: ["email"] }),
        raw_user_meta_data: jsonb({}),
        created_at: at(u.created_at),
        updated_at: at(u.created_at),
        confirmation_token: "",
        recovery_token: "",
        email_change_token_new: "",
        email_change: "",
      })),
    ),
    insert(
      "auth.identities",
      scenario.authUsers.map((u) => ({
        id: u.id,
        user_id: u.id,
        provider_id: u.id,
        provider: "email",
        identity_data: jsonb({ sub: u.id, email: u.email, email_verified: true }),
        last_sign_in_at: at(u.created_at),
        created_at: at(u.created_at),
        updated_at: at(u.created_at),
      })),
    ),
  ];

  // handle_new_user() has already created a bare profile for each auth user, so fill it in.
  const profiles = insert(
    "public.profiles",
    scenario.profiles.map((p) => ({
      id: p.id,
      username: p.username,
      display_name: p.display_name,
      last_name: p.last_name,
      neighborhood: p.neighborhood,
      avatar_url: p.avatar_url,
      singing_voice: p.singing_voice,
      instruments: textArray(p.instruments),
      instrument_levels: jsonb(p.instrument_levels),
      favorite_genres: textArray(p.favorite_genres),
      role: raw(`${literal(p.role)}::public.user_role`),
      can_host_official: p.can_host_official,
      created_at: at(p.created_at),
    })),
    `on conflict (id) do update set
  username = excluded.username, display_name = excluded.display_name, last_name = excluded.last_name,
  neighborhood = excluded.neighborhood, avatar_url = excluded.avatar_url, singing_voice = excluded.singing_voice,
  instruments = excluded.instruments, instrument_levels = excluded.instrument_levels,
  favorite_genres = excluded.favorite_genres, role = excluded.role,
  can_host_official = excluded.can_host_official, created_at = excluded.created_at`,
  );

  const songs = [
    insert("public.people", scenario.people.map((p) => ({ id: p.id, name: p.name }))),
    insert("public.artists", scenario.artists.map((a) => ({ id: a.id, name: a.name }))),
    insert(
      "public.songs",
      scenario.songs.map((s) => ({
        id: s.id, title: s.title, slug: s.slug, display_artist: s.display_artist, first_line: s.first_line,
        year: s.year, tonality: s.tonality, meter: s.meter, vibe: s.vibe, youtube_url: s.youtube_url,
        chord_chart_url: s.chord_chart_url,
      })),
    ),
    insert("public.song_composers", scenario.songComposers.map((r) => ({ song_id: r.song_id, person_id: r.person_id }))),
    insert(
      "public.song_recording_artists",
      scenario.songRecordingArtists.map((r) => ({ song_id: r.song_id, artist_id: r.artist_id, year: r.year, position: r.position })),
    ),
    insert("public.song_tags", scenario.songTags.map((r) => ({ song_id: r.song_id, tag_id: tagId(r.tag_type, r.tag_name) }))),
  ];

  const repertoire = insert(
    "public.user_songs",
    scenario.userSongs.map((r) => ({ user_id: r.user_id, song_id: r.song_id, confidence: r.confidence, key_note: r.key_note })),
  );

  const jams = [
    insert(
      "public.jams",
      scenario.jams.map((j) => ({
        id: j.id, short_code: j.short_code, name: j.name, host_user_id: j.host_user_id, visibility: j.visibility,
        starts_at: at(j.starts_at), ends_at: at(j.ends_at), timezone: j.timezone, neighborhood: j.neighborhood,
        full_address: j.full_address, notes: j.notes, capacity: j.capacity, ticket_limit: j.ticket_limit,
        guests_can_invite: j.guests_can_invite, image_url: j.image_url, created_at: at(j.created_at),
      })),
    ),
    insert("public.jam_tags", scenario.jamTags.map((r) => ({ jam_id: r.jam_id, tag_id: tagId(r.tag_type, r.tag_name) }))),
    insert("public.jam_cohosts", scenario.jamCohosts.map((r) => ({ id: r.id, jam_id: r.jam_id, user_id: r.user_id, added_by: r.added_by }))),
    insert(
      "public.jam_rsvps",
      scenario.jamRsvps.map((r) => ({
        id: r.id, jam_id: r.jam_id, user_id: r.user_id, status: r.status, waitlist_position: r.waitlist_position, created_at: at(r.created_at),
      })),
    ),
    insert(
      "public.jam_invites",
      scenario.jamInvites.map((r) => ({
        id: r.id, jam_id: r.jam_id, invited_user_id: r.invited_user_id, invited_by: r.invited_by, status: r.status, created_at: at(r.created_at),
      })),
    ),
  ];

  const sets = [
    insert(
      "public.sets",
      scenario.sets.map((s) => ({
        id: s.id, short_code: s.short_code, name: s.name, description: s.description, owner_user_id: s.owner_user_id,
        jam_id: s.jam_id, link_sharing: s.link_sharing, created_at: at(s.created_at), updated_at: at(s.created_at),
      })),
    ),
    insert(
      "public.set_songs",
      scenario.setSongs.map((r) => ({
        id: r.id, set_id: r.set_id, song_id: r.song_id, position: r.position, added_by_user_id: r.added_by_user_id,
        key_note: r.key_note, leader_user_ids: uuidArray(r.leader_user_ids), played: r.played, notes: r.notes,
      })),
    ),
    insert(
      "public.set_collaborators",
      scenario.setCollaborators.map((r) => ({
        id: r.id, set_id: r.set_id, user_id: r.user_id, invited_by: r.invited_by, role: r.role, status: r.status,
      })),
    ),
  ];

  const tickets = [
    insert(
      "public.ticket_types",
      scenario.ticketTypes.map((t) => ({
        id: t.id, jam_id: t.jam_id, name: t.name, description: t.description, price_cents: t.price_cents,
        quantity: t.quantity, sort_order: t.sort_order,
      })),
    ),
    insert(
      "public.ticket_orders",
      scenario.ticketOrders.map((o) => ({
        id: o.id, jam_id: o.jam_id, buyer_user_id: o.buyer_user_id, buyer_email: o.buyer_email, buyer_name: o.buyer_name,
        status: o.status, amount_cents: o.amount_cents, stripe_fee_cents: o.stripe_fee_cents,
        stripe_checkout_session_id: o.stripe_checkout_session_id, stripe_payment_intent_id: o.stripe_payment_intent_id,
        expires_at: at(o.expires_at), paid_at: at(o.paid_at), created_at: at(o.created_at), updated_at: at(o.created_at),
      })),
    ),
    insert(
      "public.tickets",
      scenario.tickets.map((t) => ({
        id: t.id, order_id: t.order_id, ticket_type_id: t.ticket_type_id, jam_id: t.jam_id, holder_user_id: t.holder_user_id,
        holder_name: t.holder_name, holder_email: t.holder_email, checked_in_at: at(t.checked_in_at),
      })),
    ),
    insert(
      "public.event_attendance",
      scenario.eventAttendance.map((a) => ({
        id: a.id, jam_id: a.jam_id, email: a.email, user_id: a.user_id, name: a.name, source: a.source, created_at: at(a.created_at),
      })),
    ),
  ];

  const notifications = insert(
    "public.notifications",
    scenario.notifications.map((n) => ({
      id: n.id, user_id: n.user_id, type: n.type, title: n.title, body: n.body, link: n.link, read: n.read, created_at: at(n.created_at),
    })),
  );

  const files: [string, string[]][] = [
    ["00_auth.sql", auth],
    ["01_profiles.sql", [profiles]],
    ["02_songs.sql", songs],
    ["03_repertoire.sql", [repertoire]],
    ["04_jams.sql", jams],
    ["05_sets.sql", sets],
    ["06_tickets.sql", tickets],
    ["07_notifications.sql", [notifications]],
  ];
  return files.map(([name, parts]) => ({ name, sql: `${HEADER}\n${parts.join("\n")}` }));
}
