-- Migration 189: keep every recording's YouTube link an official upload.
-- A link qualifies when it is the artist's own, "<Artist> - Topic" or VEVO
-- channel and the video names the song (isOfficialYouTubeUpload in core).
--   youtube_ok          true/false once checked; null = not yet checked
--   youtube_checked_at  last time the youtube-backfill job searched for a link
-- The hourly youtube-backfill function fills missing links, then replaces ones
-- that fail the rule, keeping the old link until a qualifying one is found.

alter table public.song_recording_artists
  add column if not exists youtube_ok boolean,
  add column if not exists youtube_checked_at timestamptz;

-- A hand-edited link has to be re-checked.
create or replace function public.reset_youtube_check() returns trigger
language plpgsql as $$
begin
  if new.youtube_url is distinct from old.youtube_url and new.youtube_ok is not distinct from old.youtube_ok then
    new.youtube_ok := null;
    new.youtube_checked_at := null;
  end if;
  return new;
end $$;

drop trigger if exists reset_youtube_check on public.song_recording_artists;
create trigger reset_youtube_check
  before update of youtube_url on public.song_recording_artists
  for each row execute function public.reset_youtube_check();

